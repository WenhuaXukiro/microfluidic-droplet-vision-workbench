  const reverse = new Map(Object.entries(english).map(([zh, en]) => [en, zh]));
  let language = 'zh-CN';
  try { if (global.localStorage?.getItem('dropletLanguage') === 'en') language = 'en'; } catch (_) {}

  function t(message, variables = {}) {
    const template = language === 'en' ? (english[message] ?? message) : message;
    return String(template).replace(/\{(\w+)\}/g, (match, key) => {
      const value = variables[key];
      if (value === undefined) return match;
      return value && typeof value === 'object' && value.i18n ? t(value.i18n, value.variables) : String(value);
    });
  }

  function translateError(message) {
    message = String(message);
    const key = reverse.get(message) ?? message;
    if (Object.hasOwn(english, key)) return t(key);
    for (const prefix of ['处理图必须与原图使用相同的数据集合：', '同源处理图必须使用相同的数据集合：', '同一实验批次不能分到不同集合：']) {
      if (message.startsWith(prefix)) return t(prefix) + message.slice(prefix.length);
    }
    const prediction = message.match(/^单液滴分类：(.+) · ([\d.]+%)（需人工审核）$/);
    if (prediction && language === 'en') return `Single-droplet classification: ${prediction[1]} · ${prediction[2]} (review required)`;
    return message;
  }

  function setText(element, message, variables = {}) {
    if (typeof element === 'string') element = global.document.getElementById(element);
    if (!element) return;
    element.setAttribute?.('data-i18n', message);
    element.setAttribute?.('data-i18n-params', JSON.stringify(variables));
    element.textContent = t(message, variables);
  }

  function apply(root = global.document) {
    for (const element of root.querySelectorAll('[data-i18n]')) {
      let variables = {};
      try { variables = JSON.parse(element.getAttribute('data-i18n-params') || '{}'); } catch (_) {}
      element.textContent = t(element.getAttribute('data-i18n'), variables);
    }
    for (const attribute of ['placeholder', 'aria-label', 'alt', 'title']) {
      for (const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) {
        element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
      }
    }
    if (root === global.document) root.documentElement.lang = language;
  }

